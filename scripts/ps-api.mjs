#!/usr/bin/env node
// The public PostScript API, read from the library source, and the check
// that docs/postscript-api.md covers it.
//
//   node scripts/ps-api.mjs           print the index of public names
//   node scripts/ps-api.mjs --write    rewrite the generated index in the doc
//   node scripts/ps-api.mjs --check    exit 1 if the index is stale or a public
//                                      name has no hand-written entry
//
// A public name is one defined at the start of a line (`/sm-name ...`) in
// lib/*.ps, minus the private prefixes below: the layout's sm-ae-, the
// ABC parser's sm-abcp-, the MusicXML parser's sm-mxp-, the ribbon's sm-rb-,
// lib/sheet.ps's sm-sh-, the transposer's sm-tr- and the performance's sm-pf-.
// tests/ps-api.test.mjs runs the check.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DOC = path.join(root, 'docs/postscript-api.md');
export const PRIVATE = ['sm-ae-', 'sm-abcp-', 'sm-rb-', 'sm-sh-', 'sm-tr-', 'sm-pf-', 'sm-mxp-'];
const BEGIN = '<!-- ps-api:index:begin (generated by node scripts/ps-api.mjs --write; do not edit) -->';
const END = '<!-- ps-api:index:end -->';

/** Every public sm- name: { name, file, line, proc, note } in file order. */
export function publicNames() {
  const files = readdirSync(path.join(root, 'lib')).filter((f) => f.endsWith('.ps')).sort();
  const seen = new Set();
  const out = [];
  for (const f of files) {
    const lines = readFileSync(path.join(root, 'lib', f), 'utf8').split('\n');
    lines.forEach((l, i) => {
      const m = /^\/(sm-[A-Za-z0-9-]+)(?=[\s{(\[<]|$)/.exec(l);
      if (!m || PRIVATE.some((p) => m[1].startsWith(p)) || seen.has(m[1])) return;
      seen.add(m[1]);
      const prev = (lines[i - 1] || '').trim();
      // the comment line just above, when it is about this name
      const note = prev.startsWith('%') && new RegExp(`(^|[^\\w-])${m[1]}($|[^\\w-])`).test(prev) ? prev.replace(/^%+\s*/, '') : '';
      out.push({ name: m[1], file: `lib/${f}`, line: i + 1, proc: /^\/\S+\s*\{/.test(l), note });
    });
  }
  return out;
}

const cell = (s) => s.replace(/\|/g, '\\|');
export function indexMarkdown(names = publicNames()) {
  const rows = names.map((n) => `| \`${n.name}\` | ${n.proc ? 'proc' : 'value'} | [${n.file}](../${n.file}#L${n.line}) | ${cell(n.note)} |`);
  return [BEGIN, '', '| Name | Kind | Defined in | Source comment |', '|---|---|---|---|', ...rows, '', END].join('\n');
}

/** Problems with the doc: [] when it is complete and its index is current. */
export function check(doc = readFileSync(DOC, 'utf8')) {
  const problems = [];
  const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
  if (a < 0 || b < a) return ['docs/postscript-api.md has no generated index (node scripts/ps-api.mjs --write)'];
  const names = publicNames();
  if (doc.slice(a, b + END.length) !== indexMarkdown(names)) problems.push('the generated index is stale: run node scripts/ps-api.mjs --write');
  const prose = doc.slice(0, a) + doc.slice(b + END.length);
  for (const n of names) {
    if (!new RegExp('`[^`\\n]*(?<![\\w-])' + n.name.replace(/-/g, '\\-') + '(?![\\w-])[^`\\n]*`').test(prose)) {
      problems.push(`${n.name} (${n.file}:${n.line}) has no entry in docs/postscript-api.md`);
    }
  }
  return problems;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = process.argv[2];
  if (arg === '--write') {
    const doc = readFileSync(DOC, 'utf8');
    const a = doc.indexOf(BEGIN), b = doc.indexOf(END);
    if (a < 0 || b < a) { console.error(`no index markers in ${DOC}`); process.exit(1); }
    writeFileSync(DOC, doc.slice(0, a) + indexMarkdown() + doc.slice(b + END.length));
    const left = check();
    left.forEach((p) => console.error(p));
    process.exit(left.length ? 1 : 0);
  } else if (arg === '--check') {
    const p = check();
    p.forEach((x) => console.error(x));
    if (!p.length) console.log(`docs/postscript-api.md covers all ${publicNames().length} public names`);
    process.exit(p.length ? 1 : 0);
  } else {
    for (const n of publicNames()) console.log(`${n.name}\t${n.proc ? 'proc' : 'value'}\t${n.file}:${n.line}\t${n.note}`);
  }
}
